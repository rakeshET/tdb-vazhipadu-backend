CREATE TABLE temple (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL
);

CREATE TABLE offering (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    temple_id BIGINT         NOT NULL REFERENCES temple (id),
    name      VARCHAR(100)   NOT NULL,
    name_key  VARCHAR(100) GENERATED ALWAYS AS (LOWER(name)),
    price     DECIMAL(10, 2) NOT NULL CHECK (price > 0),
    active    BOOLEAN        NOT NULL,
    CONSTRAINT uq_offering_temple_name UNIQUE (temple_id, name_key)
);

CREATE TABLE orders (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    temple_id     BIGINT                   NOT NULL REFERENCES temple (id),
    devotee_name  VARCHAR(100)             NOT NULL,
    phone         VARCHAR(10)              NOT NULL,
    nakshatra     VARCHAR(20)              NOT NULL,
    offering_date DATE                     NOT NULL,
    status        VARCHAR(20)              NOT NULL,
    total_amount  DECIMAL(14, 2)           NOT NULL,
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_orders_temple_date ON orders (temple_id, offering_date, id);
CREATE INDEX idx_orders_temple_status ON orders (temple_id, status, id);
CREATE INDEX idx_orders_temple_phone ON orders (temple_id, phone, id);

CREATE TABLE order_item (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      BIGINT         NOT NULL REFERENCES orders (id),
    offering_id   BIGINT         NOT NULL REFERENCES offering (id),
    offering_name VARCHAR(100)   NOT NULL,
    quantity      INTEGER        NOT NULL CHECK (quantity > 0),
    unit_price    DECIMAL(10, 2) NOT NULL,
    line_total    DECIMAL(14, 2) NOT NULL
);

CREATE INDEX idx_order_item_order ON order_item (order_id);
CREATE INDEX idx_order_item_offering ON order_item (offering_id);
